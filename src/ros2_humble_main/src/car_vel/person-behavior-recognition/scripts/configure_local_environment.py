"""Record machine-local paths without editing committed inference settings."""
import argparse
import json
from pathlib import Path
import shlex


def configure(root, prefix):
    root, prefix = Path(root).resolve(), Path(prefix).resolve()
    if not (prefix / "conda-meta").is_dir() or not (prefix / "bin/python").is_file():
        raise ValueError("Expected an existing Linux Conda environment: " + str(prefix))
    config = root / "config"
    config.mkdir(parents=True, exist_ok=True)
    # JSON is also YAML; JSON quoting handles spaces, apostrophes and backslashes.
    params = {"pphuman_recognition": {"ros__parameters": {"worker_python": str(prefix / "bin/python")}}}
    contents = {
        "local.env.sh": "# Generated by setup_ubuntu.sh; local to this machine.\n"
                        + "export PPHUMAN_CONDA_PREFIX=" + shlex.quote(str(prefix)) + "\n",
        "ros.local.yaml": json.dumps(params, ensure_ascii=False, indent=2) + "\n",
    }
    for name, text in contents.items():
        target = config / name
        temporary = target.with_name(name + ".tmp")
        temporary.write_text(text, encoding="utf-8", newline="\n")
        temporary.replace(target)
    return params


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--prefix", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(configure(args.root, args.prefix), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
