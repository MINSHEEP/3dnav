'use strict';

const fs = require('fs');
const path = require('path');
const assert = require('assert');
const vm = require('vm');

const frontend = path.join(__dirname, '..', 'car_vel', 'web_frontend');
const navigation = fs.readFileSync(
  path.join(frontend, 'navigation.html'), 'utf8');
const common = fs.readFileSync(
  path.join(frontend, 'robot_ui_common.js'), 'utf8');
const root = path.join(__dirname, '..', '..', 'nav_service');
const interfaces = fs.readFileSync(
  path.join(root, 'lzp_interface', 'CMakeLists.txt'), 'utf8');
const service = fs.readFileSync(
  path.join(root, 'lzp_service', 'lzp_service', 'map_save_service.py'), 'utf8');
const manager = fs.readFileSync(
  path.join(root, 'lzp_service', 'lzp_service', 'route_navigation_manager.py'), 'utf8');

function requireMatch(value, pattern, message) {
  if (!pattern.test(value)) throw new Error(message);
}

requireMatch(common, /rebuildTerrain:\s*'lzp_interface\/srv\/RebuildTerrain'/,
  'shared ROS types must expose RebuildTerrain');
requireMatch(interfaces, /srv\/RebuildTerrain\.srv/,
  'RebuildTerrain must be generated by lzp_interface');
requireMatch(service, /['"]\/rebuild_terrain['"]/,
  'map save backend must expose the rebuild service');
requireMatch(service, /clustered_measured_ground_v3/,
  'terrain rebuild must record the corrected surface algorithm');
requireMatch(navigation, /id="btn-rebuild-terrain"/,
  'navigation map selection must include the terrain rebuild button');
requireMatch(navigation,
  /session\.call\(\s*['"]\/rebuild_terrain['"],\s*UI\.TYPES\.rebuildTerrain/,
  'terrain rebuild button must call the backend service');
requireMatch(navigation, /屋顶、树冠等高空回波/,
  'the UI must explain which false surfaces are corrected');
requireMatch(manager, /validate_navigation_goal/,
  'the navigation owner must validate target connectivity');
requireMatch(manager, /['"]\/terrain_costmap['"]/,
  'the navigation owner must use the fused traversability map');
requireMatch(navigation, /goal_rejected_goal_disconnected/,
  'the UI must distinguish disconnected targets');
requireMatch(navigation, /goal_rejected_goal_blocked/,
  'the UI must distinguish blocked targets');

// A heartbeat for the old generation cannot authorize rebuilt terrain.
const identity = navigation.match(/function trackCurrentMapLoadIdentity\(message\) \{[^]*?\n    \}/)[0];
const issue = navigation.match(/function threeDInteractionIssue\(nowMs = Date\.now\(\)\) \{[^]*?\n    \}/)[0];
const context = {
  savedMapCloud: null,
  terrainReloadRequired: { mapName: 'map_a', loadId: 'old' },
  currentMapLoadName: 'map_a', currentMapLoadId: 'old',
  loadedMapName: 'map_a', pendingMapName: '', navigationMapReady: true,
  navigationMapView: '3d', navigationPointCloudViewer: {},
  session: { connected: true },
  invalidateDisplayedNavigationCloud() {}, tryAcceptNavigationGlobalCloud() {},
  updateMapReadyUi() {},
};
vm.createContext(context);
vm.runInContext(identity + '\n' + issue, context);
context.trackCurrentMapLoadIdentity({ success: true, map_name: 'map_a', load_id: 'old' });
assert(context.terrainReloadRequired, 'old announcement must not unblock rebuild');
assert(context.threeDInteractionIssue().includes('重新点击'), 'explain required explicit reload');
context.trackCurrentMapLoadIdentity({ success: true, map_name: 'map_a', load_id: 'new' });
assert.strictEqual(context.terrainReloadRequired, null, 'new load generation releases rebuild latch');
requireMatch(navigation, /clearThreeDRoutePreview\('地形已重建/,
  'terrain rebuild must invalidate route previews');

console.log('terrain rebuild and goal-preflight frontend contracts passed');
